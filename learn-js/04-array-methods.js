// ============================================
// .forEach() — วนทำอะไรบางอย่างกับทุกชิ้น
// ============================================
// ตัวอย่าง:
let fruits = ["แอปเปิ้ล", "กล้วย", "ส้ม"]
fruits.forEach(function(item) {
  console.log("ผลไม้:", item)
})

// โจทย์ 1:
// มี quests = ["อ่านหนังสือ", "ออกกำลังกาย", "เขียนโค้ด", "นั่งสมาธิ"]
// ให้ log ออกมาแบบนี้:
// "✅ อ่านหนังสือ"
// "✅ ออกกำลังกาย"
// ...

let quests = ["อ่านหนังสือ", "ออกกำลังกาย", "เขียนโค้ด", "นั่งสมาธิ"]

// เขียนด้านล่าง:

quests.forEach(function(item) {
  console.log("✅:", item)
})


// ============================================
// .map() — แปลงทุกชิ้นแล้วได้ array ใหม่
// ============================================
// ตัวอย่าง:
let nums = [1, 2, 3, 4]
let doubled = nums.map(function(n) {
  return n * 2
})
console.log(doubled) // → [2, 4, 6, 8]

// โจทย์ 2:
// มี scores = [40, 75, 90, 55, 88]
// แปลงทุกตัวให้ได้ XP = score * 10
// แล้ว log array ใหม่ออกมา

let scores = [40, 75, 90, 55, 88]

// เขียนด้านล่าง:

let xp = scores.map(function(n) {
  return n * 10
})
console.log(xp)


// ============================================
// .filter() — กรองเอาแค่ชิ้นที่ผ่านเงื่อนไข
// ============================================
// ตัวอย่าง:
let allNums = [1, 2, 3, 4, 5, 6]
let evenNums = allNums.filter(function(n) {
  return n % 2 === 0
})
console.log(evenNums) // → [2, 4, 6]

// โจทย์ 3:
// จาก scores = [40, 75, 90, 55, 88]
// กรองเอาแค่คนที่ได้ >= 70 (ผ่าน)
// แล้ว log ออกมา

// เขียนด้านล่าง:
let allscores = [40, 75, 90, 55, 88]
let evenscores = allscores.filter(function(n) {
  return n >=70
})

evenscores.forEach(function(n) {
  console.log(n + "ผ่าน")
})
