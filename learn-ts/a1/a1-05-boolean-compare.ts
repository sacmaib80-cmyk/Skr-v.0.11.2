// ── ตัวอย่าง ──────────────────────────────────────────────
let x: number = 5;
let y: number = 8;

console.log(x === y);      // false  (5 เท่ากับ 8 ไหม → ไม่)
console.log(x < y);        // true
console.log(x > 0 && y > 0); // true  (ทั้งคู่ต้องจริง)
console.log(!(x === y));   // true  (! กลับค่าจาก false เป็น true)


