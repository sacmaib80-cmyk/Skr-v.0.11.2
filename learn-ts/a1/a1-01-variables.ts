// ── ตัวอย่าง (อ่านให้เข้าใจก่อน) ──────────────────────────
let exampleName: string = "Fluke";
let exampleAge: number = 25;
let exampleActive: boolean = true;

console.log(exampleName);   // Fluke
console.log(exampleAge);    // 25
console.log(exampleActive); // true


