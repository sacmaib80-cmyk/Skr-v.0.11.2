// ── ตัวอย่าง ──────────────────────────────────────────────
let first: string = "Sakura";
let last: string = "Q";

console.log(first + last);            // SakuraQ  (ต่อด้วย +)
console.log(`ชื่อแอปคือ ${first}${last}`); // ชื่อแอปคือ SakuraQ  (template literal)
console.log(first.length);            // 6  (Sakura มี 6 ตัวอักษร)


