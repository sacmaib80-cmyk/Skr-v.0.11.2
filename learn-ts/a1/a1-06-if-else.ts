// ── ตัวอย่าง ──────────────────────────────────────────────
let temp: number = 32;

if (temp >= 30) {
  console.log("ร้อน");
} else {
  console.log("ไม่ร้อน");
}
// → ร้อน


let score: number = 75;

if (score >= 80) {
  console.log("A");
} else if (score >= 50) {
  console.log("B");
} else {
  console.log("F");
}
// → B


